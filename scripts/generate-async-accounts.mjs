// Keep local and hosted account rules identical. Regenerate after editing service.mjs.
import ts from '../server/node_modules/typescript/lib/typescript.js';
import {readFile,writeFile} from 'node:fs/promises';
const input=(await readFile('server/service.mjs','utf8')).replace("import {DatabaseSync} from 'node:sqlite';",'').replace('export class Accounts','export class AsyncAccounts').replace('this.db=new DatabaseSync(file)','this.db=file');
const source=ts.createSourceFile('async-service.mjs',input,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
const result=ts.transform(source,[context=>{
 const f=context.factory;
 const visit=node=>{
  if(ts.isClassDeclaration(node)&&node.name?.text==='ApiError')return undefined;
  if(ts.isConstructorDeclaration(node)){
   const constructorVisit=n=>{
    if(ts.isCallExpression(n)&&ts.isPropertyAccessExpression(n.expression)&&n.expression.getText(source)==='this.db.exec')return f.createBinaryExpression(f.createPropertyAccessExpression(f.createThis(),'ready'),f.createToken(ts.SyntaxKind.EqualsToken),n);
    return ts.visitEachChild(n,constructorVisit,context);
   };
   return ts.visitEachChild(node,constructorVisit,context);
  }
  if(ts.isMethodDeclaration(node)&&node.name.getText(source)!=='publicUser')return f.updateMethodDeclaration(node,[...(node.modifiers||[]).filter(m=>m.kind!==ts.SyntaxKind.AsyncKeyword),f.createModifier(ts.SyntaxKind.AsyncKeyword)],node.asteriskToken,node.name,node.questionToken,node.typeParameters,node.parameters,node.type,ts.visitNode(node.body,visit));
  if(ts.isCallExpression(node)&&ts.isPropertyAccessExpression(node.expression)){
   const expr=node.expression.getText(source);
   if(expr==='this.authorize'||expr==='this.setupNeeded'||expr==='this.db.exec'||expr==='this.db.close'||(/^this\.db\.prepare\(/.test(expr)&&/\.(get|all|run)$/.test(expr)))return f.createAwaitExpression(ts.visitEachChild(node,visit,context));
  }
  return ts.visitEachChild(node,visit,context);
 };
 return node=>ts.visitNode(node,visit);
}]);
await writeFile('server/async-service.mjs','// Generated by scripts/generate-async-accounts.mjs. Edit service.mjs, then regenerate.\nimport {ApiError} from "./service.mjs";\n'+ts.createPrinter().printFile(result.transformed[0]));result.dispose();
